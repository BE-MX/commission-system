import { financeClient as api } from './clients'
export const getFinanceReference = (config = {}) => api.get('/reference-data', config)
export const getFinanceCustomerOptions = (params, config = {}) => api.get('/customer-options', { ...config, params })
export const getFinanceOrderOptions = (params, config = {}) => api.get('/order-options', { ...config, params })
export const getPayments = (params, config = {}) => api.get('/payments', { ...config, params })
export const getPayment = (id, config = {}) => api.get(`/payments/${id}`, config)
export const registerPayment = body => api.post('/payments', body)
export const confirmPayment = (id, body) => api.post(`/payments/${id}/confirm`, body)
export const voidPayment = (id, body) => api.post(`/payments/${id}/void`, body)
export const refundPayment = (id, body) => api.post(`/payments/${id}/refund`, body)
export const allocatePayment = (id, body) => api.post(`/payments/${id}/allocations`, body)
export const reverseAllocation = (id, body) => api.post(`/allocations/${id}/reverse`, body)
export const getReceivables = (id, config = {}) => api.get(`/invoices/${id}/receivables`, config)
export const adjustReceivable = (id, body) => api.post(`/receivables/${id}/adjust`, body)
export const setReceivableDueDate = (id, body) => api.put(`/receivables/${id}/due-date`, body)
export const writeCurrency = body => api.put('/currencies', body)
export const writeBankAccount = body => api.put('/bank-accounts', body)
export const closeFinancePeriod = body => api.post('/close-period', body)
export const getFinanceAging = (config = {}) => api.get('/aging', config)
export const getFinanceReconciliation = (config = {}) => api.get('/reconciliation', config)
